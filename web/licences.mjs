// Open-source notices for everything bundled into the app.
//
// npm packages are taken from esbuild's metafile, so the list always matches what was
// actually bundled; their licence texts come from node_modules. The build fails if a
// bundled package has no licence file. Everything else (Pyodide, Python and the
// libraries built into it, Go for the Windows exe) is listed in licenses/components.json.
import fs from "node:fs";
import path from "node:path";

const LICENCE_FILE = /^(licen[cs]e|copying)([-.](md|txt|mit))?$/i;

function packagesIn(metafile, webDir) {
  const dirs = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const p = input.replace(/\\/g, "/");
    const i = p.lastIndexOf("node_modules/");
    if (i < 0) continue;
    const rest = p.slice(i + "node_modules/".length).split("/");
    const name = rest[0].startsWith("@") ? rest.slice(0, 2).join("/") : rest[0];
    dirs.set(name, path.join(webDir, p.slice(0, i), "node_modules", name));
  }
  return dirs;
}

function repoUrl(pkg) {
  let u = pkg.homepage || (typeof pkg.repository === "string" ? pkg.repository : pkg.repository && pkg.repository.url) || "";
  u = u.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/");
  if (/^[\w-]+\/[\w.-]+$/.test(u)) u = "https://github.com/" + u;
  return u.replace(/#readme$/, "");
}

function npmEntries(metafile, webDir) {
  const out = [];
  for (const [name, dir] of [...packagesIn(metafile, webDir)].sort(([a], [b]) => a.localeCompare(b))) {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const file = fs.readdirSync(dir).find((f) => LICENCE_FILE.test(f));
    if (!file) throw new Error(`${name} is bundled into the app but has no licence file in ${dir}`);
    const license = typeof pkg.license === "string" ? pkg.license : (pkg.license && pkg.license.type) || "see text";
    out.push({ name, version: pkg.version, license, url: repoUrl(pkg), text: fs.readFileSync(path.join(dir, file), "utf8").trim() });
  }
  return out;
}

// Packages with identical licence texts (CodeMirror's, Lezer's) are listed together.
function group(entries) {
  const groups = new Map();
  for (const e of entries) {
    const key = e.text.replace(/\s+/g, " ");
    if (!groups.has(key)) groups.set(key, { license: e.license, text: e.text, packages: [] });
    groups.get(key).packages.push({ name: e.name, version: e.version, url: e.url });
  }
  return [...groups.values()].map((g) => ({
    title: groupTitle(g.packages.map((p) => p.name)),
    ...g,
  }));
}

function groupTitle(names) {
  if (names.length === 1) return names[0];
  const scopes = new Set(names.map((n) => (n.startsWith("@") ? n.split("/")[0] : n)));
  if (scopes.size === 1) return `${[...scopes][0]} (${names.length} packages)`;
  return `${names[0]} and ${names.length - 1} related package${names.length > 2 ? "s" : ""}`;
}

export function makeNotices({ metafile, webDir, repoDir, pyodideDir }) {
  const pyodideVersion = JSON.parse(fs.readFileSync(path.join(pyodideDir, "package.json"), "utf8")).version;
  const pythonVersion = JSON.parse(fs.readFileSync(path.join(pyodideDir, "pyodide-lock.json"), "utf8")).info.python;
  const licDir = path.join(repoDir, "licenses");
  const { components } = JSON.parse(fs.readFileSync(path.join(licDir, "components.json"), "utf8"));
  const versions = { pyodide: pyodideVersion, python: pythonVersion };
  const runtime = components.map((c) => ({
    title: c.name,
    license: c.license,
    note: c.note,
    text: fs.readFileSync(path.join(licDir, c.file), "utf8").trim(),
    packages: [{ name: c.name, version: versions[c.version] || c.version || "", url: c.url }],
  }));
  const go = runtime.filter((g) => /^Go /.test(g.title));
  const notices = {
    app: { name: "PyNotebook", license: "MIT", text: fs.readFileSync(path.join(repoDir, "LICENSE"), "utf8").trim() },
    groups: [...runtime.filter((g) => !go.includes(g)), ...group(npmEntries(metafile, webDir)), ...go],
  };
  return { json: notices, text: noticesText(notices) };
}

function noticesText(n) {
  const rule = "=".repeat(78);
  const parts = [
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "PyNotebook (the Android app, the Windows exe and PyNotebook.html) includes the",
    "open-source software below. Each part is used under its own licence, reproduced",
    "here. PyNotebook itself is under the MIT licence (see LICENSE).",
    "",
    "Generated by web/build.mjs from what is actually bundled; don't edit by hand.",
    "",
  ];
  for (const g of n.groups) {
    parts.push(rule, g.title, "");
    for (const p of g.packages) parts.push(`  ${p.name}${p.version ? " " + p.version : ""}${p.url ? "  <" + p.url + ">" : ""}`);
    parts.push(`  Licence: ${g.license}`);
    if (g.note) parts.push(`  ${g.note}`);
    parts.push("", g.text, "");
  }
  return parts.join("\n").trimEnd() + "\n";
}
